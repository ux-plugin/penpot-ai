// Regenerates src/lib/renderer/api/google-fonts-catalog.json from the Google
// Fonts metadata snapshot (the Google Fonts Developer API `webfonts/v1` dump
// that Penpot keeps under frontend/resources/fonts/). The snapshot gives every
// family, its variants, and a direct gstatic .ttf URL per variant — the format
// Skia's `new_from_data` needs. We store a compact form keyed by a slug id:
//   { [id]: { f: family, c: category, v: [[weight, italic(0|1), urlPath], ...] } }
// where urlPath is the gstatic URL minus the shared `https://fonts.gstatic.com/s/`
// prefix (re-added by the loader). Run: node scripts/gen-font-catalog.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.resolve(here, '../../frontend/resources/fonts/gfonts.2025.11.28.json')
const OUT = path.resolve(here, '../src/lib/renderer/api/google-fonts-catalog.ts')
const GSTATIC_PREFIX = /^https?:\/\/fonts\.gstatic\.com\/s\//

// Slug = family lowercased, alphanumerics only (matches the existing ids:
// "Source Sans Pro" -> "sourcesanspro", "Roboto Mono" -> "robotomono").
const slug = (family) => family.toLowerCase().replace(/[^a-z0-9]/g, '')

// Back-compat aliases: the bundled default used the legacy id "sourcesanspro",
// but Google renamed the family to "Source Sans 3". Register the renamed family
// under the legacy id too so existing content keeps resolving.
const ALIASES = { sourcesanspro: 'Source Sans 3' }

function variantsOf(item) {
  const files = item.files ?? {}
  const out = []
  for (const v of item.variants ?? []) {
    let weight, italic
    if (v === 'regular') [weight, italic] = [400, 0]
    else if (v === 'italic') [weight, italic] = [400, 1]
    else {
      const m = /^(\d+)(italic)?$/.exec(v)
      if (!m) continue
      ;[weight, italic] = [Number(m[1]), m[2] ? 1 : 0]
    }
    const url = files[v]
    if (!url) continue
    out.push([weight, italic, url.replace(GSTATIC_PREFIX, '')])
  }
  // Sort by weight then upright-before-italic for stable nearest-variant search.
  out.sort((a, b) => a[0] - b[0] || a[1] - b[1])
  return out
}

const src = JSON.parse(fs.readFileSync(SRC, 'utf8'))
const byFamily = new Map(src.items.map((it) => [it.family, it]))

const catalog = {}
let families = 0
let variants = 0
for (const item of src.items) {
  const v = variantsOf(item)
  if (!v.length) continue
  catalog[slug(item.family)] = { f: item.family, c: item.category ?? '', v }
  families++
  variants += v.length
}
for (const [id, family] of Object.entries(ALIASES)) {
  const item = byFamily.get(family)
  if (!item || catalog[id]) continue
  const v = variantsOf(item)
  if (!v.length) continue
  catalog[id] = { f: 'Source Sans Pro', c: item.category ?? '', v }
  families++
}

const ts = `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-font-catalog.mjs — do not edit by hand.
// Full Google Fonts catalogue: family id -> { f: family, c: category,
// v: [weight, italic(0|1), gstatic url path][] }. See google-fonts.ts.
export type FontCatalogVariant = [weight: number, italic: 0 | 1, urlPath: string]
export interface FontCatalogEntry { f: string; c: string; v: FontCatalogVariant[] }
export const FONT_CATALOG_DATA: Record<string, FontCatalogEntry> = ${JSON.stringify(catalog)}
`
fs.writeFileSync(OUT, ts)
console.log(`Wrote ${OUT}`)
console.log(`families: ${families}, variants: ${variants}, bytes: ${fs.statSync(OUT).size}`)
